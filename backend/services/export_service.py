"""
Export service: generate PDF and DOCX bytes from a draft text.
"""
from __future__ import annotations

import io
from datetime import datetime

DISCLAIMER = "AI-GENERATED DRAFT – ADVOCATE REVIEW REQUIRED BEFORE USE"


def generate_pdf(draft_text: str, case_form: dict) -> bytes:
    """Return PDF bytes for the given draft."""
    from reportlab.lib.pagesizes import A4  # type: ignore
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle  # type: ignore
    from reportlab.lib.units import cm  # type: ignore
    from reportlab.lib import colors  # type: ignore
    from reportlab.platypus import (  # type: ignore
        SimpleDocTemplate, Paragraph, Spacer, HRFlowable, PageBreak
    )

    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=2.5 * cm,
        rightMargin=2.5 * cm,
        topMargin=2.5 * cm,
        bottomMargin=2.5 * cm,
        title=f"Draft - {case_form.get('client_name', 'Unknown')}",
        author="Nyay Saathi",
    )

    styles = getSampleStyleSheet()
    banner_style = ParagraphStyle(
        "Banner",
        parent=styles["Normal"],
        fontName="Times-Bold",
        fontSize=10,
        textColor=colors.HexColor("#7B3F00"),
        backColor=colors.HexColor("#FFF3CD"),
        borderColor=colors.HexColor("#FFC107"),
        borderWidth=1,
        borderPadding=6,
        leading=14,
        alignment=1,  # center
    )
    heading_style = ParagraphStyle(
        "Heading",
        parent=styles["Heading1"],
        fontName="Times-Bold",
        fontSize=14,
        leading=20,
        spaceAfter=8,
    )
    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontName="Times-Roman",
        fontSize=11,
        leading=18,
        spaceAfter=6,
    )
    footer_style = ParagraphStyle(
        "Footer",
        parent=styles["Normal"],
        fontName="Times-Italic",
        fontSize=8,
        textColor=colors.grey,
        alignment=2,  # right
    )

    story = []

    # Disclaimer banner
    story.append(Paragraph(f"⚠ {DISCLAIMER}", banner_style))
    story.append(Spacer(1, 0.4 * cm))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CCCCCC")))
    story.append(Spacer(1, 0.3 * cm))

    # Draft body — split on newlines, treat blank lines as spacers
    lines = draft_text.splitlines()
    for line in lines:
        stripped = line.strip()
        if not stripped:
            story.append(Spacer(1, 0.25 * cm))
        elif stripped.isupper() and len(stripped) < 60:
            story.append(Paragraph(stripped, heading_style))
        else:
            # Escape HTML-like characters for ReportLab
            safe = stripped.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(safe, body_style))

    story.append(Spacer(1, 0.6 * cm))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CCCCCC")))

    generated_on = datetime.now().strftime("%d %b %Y, %H:%M")
    story.append(Paragraph(f"Generated by Nyay Saathi on {generated_on}", footer_style))

    # Page number callback
    def add_page_number(canvas, doc):  # type: ignore
        canvas.saveState()
        canvas.setFont("Times-Italic", 8)
        canvas.setFillColor(colors.grey)
        canvas.drawRightString(
            A4[0] - 2.5 * cm,
            1.5 * cm,
            f"Page {doc.page}",
        )
        canvas.restoreState()

    doc.build(story, onFirstPage=add_page_number, onLaterPages=add_page_number)
    return buffer.getvalue()


def generate_docx(draft_text: str, case_form: dict) -> bytes:
    """Return DOCX bytes for the given draft."""
    from docx import Document  # type: ignore
    from docx.shared import Pt, RGBColor, Inches  # type: ignore
    from docx.enum.text import WD_ALIGN_PARAGRAPH  # type: ignore

    document = Document()

    # Margins
    for section in document.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1.2)
        section.right_margin = Inches(1.2)

    # Disclaimer banner paragraph
    banner_para = document.add_paragraph()
    banner_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    banner_run = banner_para.add_run(f"⚠  {DISCLAIMER}")
    banner_run.bold = True
    banner_run.font.size = Pt(10)
    banner_run.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)  # red

    document.add_paragraph()  # spacer

    # Draft body
    lines = draft_text.splitlines()
    for line in lines:
        stripped = line.strip()
        if not stripped:
            document.add_paragraph()
        elif stripped.isupper() and len(stripped) < 60:
            heading = document.add_heading(stripped, level=2)
            heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
        else:
            para = document.add_paragraph(stripped)
            para.style.font.size = Pt(11)

    # Footer note
    document.add_paragraph()
    generated_on = datetime.now().strftime("%d %b %Y, %H:%M")
    footer_para = document.add_paragraph(f"Generated by Nyay Saathi on {generated_on}")
    footer_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for run in footer_para.runs:
        run.font.size = Pt(8)
        run.italic = True
        run.font.color.rgb = RGBColor(0x88, 0x88, 0x88)

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()
